/* ==========================================================================
 * 每日一言（js/daily-quote.js）—— 最高优先级
 * --------------------------------------------------------------------------
 * 优先级设计：本脚本以"遮罩元素之后的第一个同步 <script>"加载，
 * 浏览器解析到遮罩 DOM 后立即下载并执行，页面首帧绘制前完成文案注入：
 *   - 不依赖 DOMContentLoaded / window load / 任何其他脚本
 *   - 不等待图片、字体等资源；与其他组件互不阻塞
 *   - 纯 DOM 文本写入，不影响遮罩显示与入场动画
 * 数据源：内置语录数组 —— GitHub Pages 纯静态托管（无后端、无跨域）
 * 环境下 100% 可用；按日期(YYYYMMDD)稳定选取，当天固定、次日更新。
 * 降级：HTML 中已为语录轨道预置默认文案，若本脚本执行异常则静默保留
 * 默认文案，遮罩区域绝不出现空白。
 * ========================================================================== */
(function () {
    'use strict';

    var QUOTES = [
        '求知若饥，虚心若愚。—— Steve Jobs',
        'Stay hungry, stay foolish.',
        '代码如诗，简洁即美。',
        '无限进步，胜过完美停留。',
        '每一次调试，都是与逻辑的对话。',
        '把复杂留给代码，把简单留给用户。',
        '热爱可抵岁月漫长。',
        '不积跬步，无以至千里。',
        '保持好奇，保持热爱。',
        '完成比完美更重要。',
        '千里之行，始于足下。',
        '行动是治愈焦虑的良药。',
        '今天的学习，是明天的底气。',
        '慢慢来，比较快。',
        '梦想照亮前路，脚步丈量远方。',
        '星光不问赶路人，时光不负有心人。',
        '与其临渊羡鱼，不如退而结网。',
        '代码改变世界，逻辑解构真理。',
        '愿我们都能成为更好的自己。',
        '每个伟大的作品，都始于一行代码。',
        '路虽远，行则将至；事虽难，做则必成。',
        '学习是一场没有终点的旅行。'
    ];

    /** 按日期取当日语录（seed = YYYYMMDD → 稳定索引，当日固定） */
    function quoteOfTheDay() {
        var now = new Date();
        var seed = now.getFullYear() * 10000 + (now.getMonth() + 1) * 100 + now.getDate();
        return QUOTES[Math.abs(seed) % QUOTES.length];
    }

    try {
        var text = quoteOfTheDay();
        var items = document.querySelectorAll('#quote-track .loader-quote__item');
        for (var i = 0; i < items.length; i++) {
            items[i].textContent = text; // 覆盖 HTML 预置默认文案
        }
    } catch (e) {
        /* 静默降级：保留 HTML 中的默认文案，遮罩不出现空白 */
    }
})();
